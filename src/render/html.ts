/** Report label language; English is the default. */
export type ReportLang = 'en' | 'zh'

export interface HtmlRenderOptions {
  readonly argCharLimit: number
  readonly resultCharLimit: number
  /** UI label language for the report (default `'en'`). */
  readonly lang?: ReportLang
}

export const defaultHtmlOptions: HtmlRenderOptions = {
  argCharLimit: 512,
  resultCharLimit: 2048,
}

function escapeHtml(text: string): string {
  return text
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
}

function fmtTime(epochMs: number): string {
  return new Date(epochMs).toISOString().replace('T', ' ').replace(/\.\d+Z$/, 'Z')
}

function fmtTokens(n: number): string {
  if (n >= 1_000_000) return `${(n / 1_000_000).toFixed(1)}M`
  if (n >= 1_000) return `${(n / 1_000).toFixed(1)}k`
  return String(n)
}

function id8(id: string): string {
  return id.replace(/^session-/, '').slice(0, 8)
}

