function t(key: LabelKey, lang: ReportLang): string {
  return LABELS[key][lang]
}

function tf(key: LabelKey, lang: ReportLang, vars: Readonly<Record<string, string | number>>): string {
  let out = LABELS[key][lang]
  for (const [name, value] of Object.entries(vars)) {
    out = out.replaceAll(`{${name}}`, String(value))
  }
  return out
}

// ─── JSON syntax highlighting (pattern-based, no dependency) ─────────────────

const JSON_TOKEN =
  /("(?:[^"\\]|\\.)*")(\s*:)?|-?\b\d+(?:\.\d+)?(?:[eE][+-]?\d+)?\b|\b(?:true|false)\b|\bnull\b/g

/** True when the full text parses as JSON (highlight gate; truncated views still render). */
function looksLikeJson(text: string): boolean {
  if (text.length === 0) return false
  try {
    JSON.parse(text)
    return true
  } catch {
    return false
  }
}

/** Wrap JSON tokens in colored spans; every segment is HTML-escaped. */
function highlightJson(text: string): string {
  let out = ''
  let last = 0
  for (const match of text.matchAll(JSON_TOKEN)) {
    const index = match.index ?? 0
    const token = match[0] ?? ''
    out += escapeHtml(text.slice(last, index))
    if (match[2] !== undefined) {
      out += `<span class="hl-key">${escapeHtml(match[1] ?? '')}</span><span class="hl-punc">${escapeHtml(match[2])}</span>`
    } else if (token.startsWith('"')) {
      out += `<span class="hl-str">${escapeHtml(token)}</span>`
    } else if (token === 'true' || token === 'false') {
      out += `<span class="hl-bool">${token}</span>`
    } else if (token === 'null') {
      out += '<span class="hl-null">null</span>'
    } else {
      out += `<span class="hl-num">${escapeHtml(token)}</span>`
    }
    last = index + token.length
  }
  out += escapeHtml(text.slice(last))
  return out
}

/** Truncated, escaped code block — JSON gets token colors, everything else stays plain. */
function renderCode(raw: string, limit: number): string {
  const shown = truncate(raw, limit)
  return looksLikeJson(raw) ? `<code class="json">${highlightJson(shown)}</code>` : `<code>${escapeHtml(shown)}</code>`
}

