/** KPI card row: the numbers that describe the session. */
function renderKpiGrid(input: RenderInput, lang: ReportLang): string {
  const stats = input.stats
  const cards: Array<{ readonly label: LabelKey; readonly value: string; readonly note?: string; readonly tip: LabelKey }> = [
    { label: 'messages', value: String(input.totals.messages), tip: 'tipMessages' },
    {
      label: 'toolCalls',
      value: String(input.totals.toolCalls),
      note: stats !== undefined && stats.failedToolCalls > 0 ? tf('failedNote', lang, { n: stats.failedToolCalls }) : undefined,
      tip: 'tipToolCalls',
    },
    { label: 'tokensIn', value: fmtTokens(input.totals.inputTokens), tip: 'tipTokens' },
    { label: 'tokensOut', value: fmtTokens(input.totals.outputTokens), tip: 'tipTokens' },
    {
      label: 'duration',
      value: stats?.durationMs !== undefined && stats.durationMs !== null ? formatDuration(stats.durationMs) : '—',
      tip: 'tipDuration',
    },
    { label: 'turns', value: stats !== undefined ? String(stats.turns) : '—', tip: 'tipTurns' },
  ]
  const cost = stats?.cost
  if (cost !== undefined) {
    cards.push({
      label: 'cost',
      value: `${cost.currency}${cost.total >= 0.01 ? cost.total.toFixed(2) : cost.total.toFixed(4)}`,
      tip: 'tipCost',
    })
  }
  const spark = stats !== undefined ? renderSparklineSvg(stats.perAssistantTokens, lang) : ''
  return [
    '<section class="kpi-grid">',
    ...cards.map(
      ({ label, value, note, tip }) =>
        `<div class="kpi" title="${escapeHtml(t(tip, lang))}"><div class="kpi-label">${escapeHtml(t(label, lang))}</div><div class="kpi-value">${escapeHtml(value)}${
          note !== undefined ? ` <span class="kpi-note">${escapeHtml(note)}</span>` : ''
        }</div></div>`,
    ),
    spark !== ''
      ? `<div class="kpi kpi-wide" title="${escapeHtml(t('tipTokens', lang))}"><div class="kpi-label">${escapeHtml(t('sparkline', lang))}</div>${spark}</div>`
      : '',
    '</section>',
  ].join('\n')
}

/** Inline SVG bar sparkline: no JS, scales to card width, one tooltip per bar. */
function renderSparklineSvg(series: readonly number[], lang: ReportLang): string {
  if (series.length < 2) return ''
  const max = Math.max(...series)
  const W = 320
  const H = 40
  const gap = 2
  const barWidth = Math.max(1, (W - gap * (series.length - 1)) / series.length)
  const bars = series
    .map((value, index) => {
      const h = max === 0 ? 1 : Math.max(1, (value / max) * (H - 2))
      const x = index * (barWidth + gap)
      const y = H - h
      const tip = escapeHtml(tf('tipSpark', lang, { n: index + 1, v: value }))
      return `<rect x="${x.toFixed(1)}" y="${y.toFixed(1)}" width="${barWidth.toFixed(1)}" height="${h.toFixed(1)}" rx="1" title="${tip}"/>`
    })
    .join('')
  return `<svg class="sparkline" viewBox="0 0 ${W} ${H}" preserveAspectRatio="none" role="img" aria-label="${escapeHtml(t('sparkline', lang))}">${bars}</svg>`
}

/** Turn timeline: one horizontal bar per user→next-user span, colored by duration share. */
function renderTimeline(input: RenderInput, lang: ReportLang): string {
  const entries = input.entries
  const starts = entries.filter((entry) => entry.message.role === 'user' && entry.message.source.kind !== 'tool')
  const durationMs = input.stats?.durationMs
  if (starts.length < 2 || durationMs === undefined || durationMs === null) return ''
  const totalMs = durationMs
  const rows = starts.map((start, index) => {
    const end = starts[index + 1]?.time ?? entries[entries.length - 1]?.time ?? start.time
    const ms = Math.max(0, end - start.time)
    const pct = totalMs === 0 ? 0 : (ms / totalMs) * 100
    const hue = 200 - Math.min(160, (pct / 100) * 160)
    const tip = escapeHtml(tf('tipTurn', lang, { n: index + 1, d: formatDuration(ms) }))
    return `<div class="tl-row"><span class="tl-label">${escapeHtml(tf('turn', lang, { n: index + 1 }))}</span><div class="tl-track"><div class="tl-bar" style="width:${pct.toFixed(1)}%;background:hsl(${hue.toFixed(0)},65%,50%)" title="${tip}"></div></div><span class="tl-dur">${escapeHtml(formatDuration(ms))}</span></div>`
  })
  return `<section class="card"><h2>${escapeHtml(t('turnTimeline', lang))}</h2>${rows.join('')}</section>`
}

/** Tool ranking bars. */
function renderToolRanking(input: RenderInput, lang: ReportLang): string {
  const breakdown = input.stats?.toolBreakdown ?? []
  if (breakdown.length === 0) return ''
  const max = breakdown[0]?.calls ?? 1
  const rows = breakdown.slice(0, 8).map((tool) => {
    const pct = (tool.calls / max) * 100
    const fail = tool.failures > 0 ? ` <span class="fail">${tool.failures}✗</span>` : ''
    const tip = escapeHtml(`${tool.name} · ${tf('tipTool', lang, { n: tool.calls })}`)
    return `<div class="tool-row"><span class="tool-name" title="${escapeHtml(tool.name)}">${escapeHtml(tool.name)}</span><div class="tool-track"><div class="tool-bar" style="width:${pct.toFixed(1)}%" title="${tip}"></div></div><span class="tool-count">${tool.calls}${fail}</span></div>`
  })
  return `<section class="card"><h2>${escapeHtml(t('toolCallsSection', lang))}</h2>${rows.join('')}</section>`
}

function renderBlocks(blocks: readonly ContentBlock[], options: HtmlRenderOptions): string[] {
  const lang = options.lang ?? 'en'
  const parts: string[] = []
  for (const block of blocks) {
    if (block.type === 'reasoning') {
      parts.push(
        `<details class="reasoning"><summary>${escapeHtml(t('reasoning', lang))}</summary><pre>${escapeHtml(block.text.trim())}</pre></details>`,
      )
    } else if (block.type === 'text') {
      parts.push(`<div class="msg-text">${escapeHtml(block.text.trim())}</div>`)
    } else if (block.type === 'tool-call') {
      const parsed = parseToolArguments(block.arguments)
      const diff = renderToolDiff(block.name, parsed)
      if (diff) {
        parts.push(
          `<details class="tool"><summary>🔧 ${escapeHtml(block.name)}</summary><pre class="diff">${escapeHtml(truncate(diff, options.resultCharLimit))}</pre></details>`,
        )
      } else {
        parts.push(
          `<details class="tool"><summary>🔧 ${escapeHtml(block.name)}</summary><pre>${renderCode(block.arguments, options.argCharLimit)}</pre></details>`,
        )
      }
    } else if ('content' in block) {
      const inner = block.content
        .map((inner2) => (inner2.type === 'text' ? inner2.text : `(${JSON.stringify(inner2.type)})`))
        .join('\n')
      parts.push(
        `<details class="tool-result"${block.isError === true ? ' open' : ''}><summary>🧾 ${escapeHtml(t('result', lang))}</summary><pre>${renderCode(inner, options.resultCharLimit)}</pre></details>`,
      )
    } else {
      parts.push(`<div class="unsupported">(${escapeHtml(JSON.stringify(block.type))})</div>`)
    }
  }
  return parts
}

function renderEntry(entry: RenderInput['entries'][number], options: HtmlRenderOptions, errorNo?: number): string {
  const lang = options.lang ?? 'en'
  const time = escapeHtml(fmtTime(entry.time))
  const message = entry.message
  const anchor = errorNo !== undefined ? ` id="error-${errorNo}"` : ''
  // Order matches buildEntries: assistant, then tool-result, then user —
  // tool-result messages carry role 'user' with a tool source.
  if (message.role === 'assistant') {
    const assistant = asAssistant(message)
    const provenance = assistant !== undefined ? `${assistant.source.provider} / ${assistant.source.model}` : ''
    const usage =
      entry.usage !== undefined
        ? ` · ${fmtTokens(entry.usage.inputTokens)} in / ${fmtTokens(entry.usage.outputTokens)} out`
        : ''
    const body = renderBlocks(message.content, options).join('\n')
    return `<article class="entry assistant"><header>🤖 ${escapeHtml(t('assistant', lang))} <span class="prov">${escapeHtml(provenance)}${escapeHtml(usage)}</span> <time>${time}</time></header>${body}</article>`
  }
  const toolResult = asToolResult(message)
  if (toolResult !== undefined) {
    const isError = entry.error !== undefined || toolResult.content.some((block) => block.isError === true)
    const errorLine =
      entry.error !== undefined
        ? `<div class="error-banner">${escapeHtml(t('toolFailed', lang))} <code>${escapeHtml(entry.error.name)}</code> (<code>${escapeHtml(entry.error.code)}</code>)</div>`
        : ''
    const body = renderBlocks(toolResult.content, options).join('\n')
    return `<article class="entry tool-result${isError ? ' error' : ''}"${anchor}><header>🧾 ${escapeHtml(t('toolResult', lang))} <code>${escapeHtml(id8(String(toolResult.source.callId)))}</code>${isError ? ' <span class="fail">⚠ ERROR</span>' : ''} <time>${time}</time></header>${errorLine}${body}</article>`
  }
  const body = renderBlocks(message.content, options).join('\n')
  return `<article class="entry user"><header>👤 ${escapeHtml(t('user', lang))} <time>${time}</time></header>${body}</article>`
}

function renderFilterNote(input: RenderInput): string {
  if (input.filterNote === undefined) return ''
  return `<div class="filter-note">⚠ ${escapeHtml(input.filterNote)}</div>`
}

